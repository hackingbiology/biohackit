#!/usr/bin/env python3
"""Traceability matrix: OpenSpec scenarios -> tests that declare them.

A test covers a scenario by containing `scenario: <capability>::<scenario-slug>`
(comment, docstring or marker). Usage: matrix.py [--write] [--json] [--summary]
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEST_GLOBS = ["backend/**/test*.py", "frontend/src/**/*.test.ts", "frontend/src/**/*.test.tsx", "frontend/e2e/**/*.ts"]
DECL = re.compile(r"scenario:\s*((?:[a-z0-9-]+::[a-z0-9-]+\s*,?\s*)+)")


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def scenarios():
    rows = []
    sources = [(p, p.parent.name, "spec") for p in sorted((ROOT / "openspec/specs").glob("*/spec.md"))]
    for p in sorted((ROOT / "openspec/changes").glob("*/specs/*/*.md")):
        if "archive" in p.parts:
            continue
        sources.append((p, p.parent.name, "change:" + p.parts[p.parts.index("changes") + 1]))
    seen = set()
    for path, cap, origin in sources:
        req = None
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("### Requirement:"):
                req = line.split(":", 1)[1].strip()
            elif line.startswith("#### Scenario:"):
                name = line.split(":", 1)[1].strip()
                sid = f"{cap}::{slug(name)}"
                if sid in seen:
                    continue
                seen.add(sid)
                rows.append({"id": sid, "capability": cap, "requirement": req, "scenario": name,
                             "origin": origin, "file": str(path.relative_to(ROOT))})
    return rows


def declarations():
    cov = {}
    for g in TEST_GLOBS:
        for p in ROOT.glob(g):
            if "node_modules" in p.parts or ".venv" in p.parts:
                continue
            for m in DECL.finditer(p.read_text(encoding="utf-8", errors="ignore")):
                for sid in re.findall(r"[a-z0-9-]+::[a-z0-9-]+", m.group(1)):
                    cov.setdefault(sid, set()).add(str(p.relative_to(ROOT)))
    return cov


def build():
    rows, cov = scenarios(), declarations()
    for r in rows:
        r["tests"] = sorted(cov.get(r["id"], []))
    known = {r["id"] for r in rows}
    unknown = sorted(s for s in cov if s not in known)
    n, c = len(rows), sum(1 for r in rows if r["tests"])
    return {"total": n, "covered": c, "pct": round(100 * c / n, 1) if n else 0.0, "rows": rows, "unknown_ids": unknown}


def markdown(m):
    out = ["# Traceability matrix", "", f"**{m['covered']}/{m['total']} scenarios covered ({m['pct']}%)** — generated by `tools/trace/matrix.py`, do not edit.", ""]
    caps = {}
    for r in m["rows"]:
        caps.setdefault(r["capability"], []).append(r)
    out += ["| Capability | Covered |", "|---|---|"]
    for cap, rs in caps.items():
        out.append(f"| {cap} | {sum(1 for r in rs if r['tests'])}/{len(rs)} |")
    for cap, rs in caps.items():
        out += ["", f"## {cap}", "", "| | Scenario | Origin | Tests |", "|---|---|---|---|"]
        for r in rs:
            out.append(f"| {'✅' if r['tests'] else '⬜'} | `{r['id']}` | {r['origin']} | {', '.join(r['tests']) or '—'} |")
    if m["unknown_ids"]:
        out += ["", "## Test declarations with unknown scenario ids", ""] + [f"- `{u}`" for u in m["unknown_ids"]]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    m = build()
    if "--write" in sys.argv:
        (ROOT / "docs/TRACEABILITY.md").write_text(markdown(m), encoding="utf-8")
    if "--json" in sys.argv:
        print(json.dumps(m, indent=1))
    else:
        print(f"{m['covered']}/{m['total']} covered ({m['pct']}%); unknown ids: {len(m['unknown_ids'])}")
    sys.exit(1 if "--strict" in sys.argv and m["unknown_ids"] else 0)
